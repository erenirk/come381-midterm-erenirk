-- COM E381 | Ödev 1 | Otel rezervasyon sistemi şeması (PostgreSQL)
-- Yeniden çalıştırılabilir: önce eski tabloları bağımlılık sırasının tersinde siler.
-- NOT NULL / UNIQUE / CHECK ve isimli foreign key'ler week-05/constraints.sql içindedir.

DROP TABLE IF EXISTS reservation CASCADE;
DROP TABLE IF EXISTS room CASCADE;
DROP TABLE IF EXISTS hotel CASCADE;
DROP TABLE IF EXISTS room_type CASCADE;
DROP TABLE IF EXISTS guest CASCADE;

CREATE TABLE guest (
    guest_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   varchar(100),
    email       varchar(150),
    city        varchar(60),
    status      varchar(20) DEFAULT 'active',
    joined_date date DEFAULT CURRENT_DATE
);

CREATE TABLE hotel (
    hotel_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     varchar(100),
    city     varchar(60)
);

CREATE TABLE room_type (
    room_type_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(50)
);

CREATE TABLE room (
    room_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id      integer REFERENCES hotel (hotel_id),
    room_type_id  integer REFERENCES room_type (room_type_id),
    room_number   varchar(10),
    nightly_rate  numeric(10,2),
    max_occupancy integer
);

-- guest ile room arasındaki M:N ilişkiyi, her rezervasyona ait niteliklerle çözen ara tablo.
CREATE TABLE reservation (
    reservation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_id       integer REFERENCES guest (guest_id),
    room_id        integer REFERENCES room (room_id),
    booked_on      date DEFAULT CURRENT_DATE,
    check_in       date,
    check_out      date,
    guest_count    integer,
    status         varchar(20) DEFAULT 'pending',
    rating         smallint
);
